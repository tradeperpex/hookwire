// Writes src/lib/rulesAbi.ts from the Foundry build output. Run after `forge build` in contracts/.
import fs from "node:fs";
const art = JSON.parse(fs.readFileSync("contracts/out/HookwireRules.sol/HookwireRules.json", "utf8"));
const abi = art.abi.filter((x) => x.type !== "constructor");
fs.writeFileSync(
  "src/lib/rulesAbi.ts",
  `// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit.\nexport const rulesAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log("abi entries", abi.length);
